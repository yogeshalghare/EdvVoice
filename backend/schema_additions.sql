--
-- EdvVoice — additions to grievance_system.sql
--
-- Run this against the existing database. Every statement is additive:
-- nothing is dropped, nothing is renamed, and every new column is either
-- nullable or has a default, so rows already in the tables stay valid.
--
--     psql -d grievance_system -f schema_additions.sql
--
-- Safe to run more than once: every statement either checks first or
-- has IF NOT EXISTS, so a second run changes nothing and reports no error.
--
-- Why each one is here:
--
--   password_hash   The original tables have no password column, so nobody
--                   could sign in. Which table a row lives in is the role —
--                   students authenticate against students, admins against
--                   admins — so no role column is needed.
--
--   priority        The NLP layer works out urgency from the complaint text.
--                   Without somewhere to put it, the admin queue cannot be
--                   triaged.
--
--   notes           The optional "room number, time of day" field students
--                   fill in alongside the spoken complaint.
--
--   file_type       The evidence viewer needs to know whether an attachment
--   file_size       is an image, a video or audio before it renders it.
--
--   status history  The original schema keeps only the current status, so
--                   the progress timeline had nowhere to live.
--
--   reset tokens    Supports the password reset emails.
--
--   email_verified  Set once a student enters the 6-digit code emailed at
--   verification    sign-up. Only the bcrypt hash of the code is stored, and
--   tokens          'attempts' caps guessing at five tries. Enforced only when
--                   REQUIRE_EMAIL_VERIFICATION is on, so the column can exist
--                   without changing behaviour.
--
-- Note: the GRV tracking ID students quote is NOT stored. It is derived in
-- the application as 'GRV' || (1020 + complaint_id), which is stable because
-- complaint_id never changes, and saves keeping a second column in sync.
--

BEGIN;

-- --------------------------------------------------------------- accounts

ALTER TABLE public.students
    ADD COLUMN IF NOT EXISTS password_hash character varying(255) NOT NULL DEFAULT '';

ALTER TABLE public.admins
    ADD COLUMN IF NOT EXISTS password_hash character varying(255) NOT NULL DEFAULT '';

-- ------------------------------------------------------------- complaints

ALTER TABLE public.complaints
    ADD COLUMN IF NOT EXISTS priority character varying(20) NOT NULL DEFAULT 'Normal';

ALTER TABLE public.complaints
    ADD COLUMN IF NOT EXISTS notes text NOT NULL DEFAULT '';

-- ------------------------------------------------------------ attachments

ALTER TABLE public.complaint_attachments
    ADD COLUMN IF NOT EXISTS file_type character varying(100) NOT NULL DEFAULT '';

ALTER TABLE public.complaint_attachments
    ADD COLUMN IF NOT EXISTS file_size integer NOT NULL DEFAULT 0;

-- -------------------------------------------------- email verification

ALTER TABLE public.students
    ADD COLUMN IF NOT EXISTS email_verified boolean NOT NULL DEFAULT false;

-- Accounts that existed before this column did were created when there was
-- nothing to verify, so mark them verified rather than locking them out.
UPDATE public.students SET email_verified = true WHERE email_verified = false;

CREATE TABLE IF NOT EXISTS public.email_verification_tokens (
    token_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       character varying(120) NOT NULL,  -- bcrypt hash of the code
    student_id  integer NOT NULL REFERENCES public.students(student_id),
    expires_at  timestamp without time zone NOT NULL,
    used_at     timestamp without time zone,
    attempts    integer DEFAULT 0 NOT NULL
);

-- For a database where an earlier version of this table already exists.
ALTER TABLE public.email_verification_tokens
    ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_verification_student
    ON public.email_verification_tokens (student_id);

-- --------------------------------------------------------- status history

CREATE TABLE IF NOT EXISTS public.complaint_status_history (
    history_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id integer NOT NULL REFERENCES public.complaints(complaint_id),
    status       character varying(30) NOT NULL,
    note         text DEFAULT '' NOT NULL,
    changed_by   character varying(100) NOT NULL,
    changed_at   timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ---------------------------------------------------- password reset flow

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    token_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       character varying(120) NOT NULL UNIQUE,
    user_type   character varying(10) NOT NULL,   -- 'student' or 'admin'
    user_id     integer NOT NULL,
    expires_at  timestamp without time zone NOT NULL,
    used_at     timestamp without time zone
);

-- ------------------------------------------------------------- useful indexes

CREATE INDEX IF NOT EXISTS idx_complaints_student ON public.complaints (student_id);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON public.complaints (status);
CREATE INDEX IF NOT EXISTS idx_complaints_category ON public.complaints (category);
CREATE INDEX IF NOT EXISTS idx_attachments_complaint ON public.complaint_attachments (complaint_id);
CREATE INDEX IF NOT EXISTS idx_history_complaint ON public.complaint_status_history (complaint_id);

COMMIT;
