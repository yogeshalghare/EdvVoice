"""
Build the training dataset for the complaint classifier.

    python generate_dataset.py

Writes data/complaints_train.csv — around 600 labelled complaints across the
five categories.

WHY THIS EXISTS, AND WHAT TO SAY ABOUT IT
-----------------------------------------
No public dataset of Indian college grievances exists. The large public
complaint datasets (the CFPB consumer complaints database and its mirrors on
Kaggle) are about mortgages, credit cards and debt collection — the
vocabulary does not overlap with hostel taps and marksheets, and the labels
do not map to our five departments.

So this file generates a seed dataset instead. It is SYNTHETIC and must be
described that way in the report. The honest framing is: the model is
bootstrapped on generated data and retrained on real complaints once the
system is deployed and students have filed some.

HOW IT AVOIDS THE OBVIOUS TRAP
------------------------------
Generated data is usually templated, and a model trained on templates learns
the template rather than the language. Four things work against that here:

  1. Many sentence frames per category (not one), with different word order,
     tense, politeness and length.
  2. Slot vocabularies — place, object, time, symptom — combined randomly, so
     the same frame rarely produces the same sentence twice.
  3. Optional prefixes, suffixes and filler that students actually say.
  4. Deliberate overlap between categories: words like "water", "fee" and
     "room" appear under more than one label, so the model cannot win by
     memorising single keywords.

Even so, accuracy measured on data generated by this same file would be
dishonestly high. That is what data/complaints_test.csv is for: a separate
hand-written test set this script never touches. Report THAT number.
"""

