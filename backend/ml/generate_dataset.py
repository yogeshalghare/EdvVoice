def fill(frame: str) -> str:
    """Fill every {slot} in a frame with a random value."""
    out = frame
    for slot, values in SLOTS.items():
        token = "{" + slot + "}"
        while token in out:
            out = out.replace(token, random.choice(values), 1)
    return out


def decorate(sentence: str) -> str:
    """Add the openings, closings and filler students actually use."""
    text = random.choice(POLITE_OPEN) + sentence

    # Lowercase the frame's first letter when a prefix now precedes it.
    if text != sentence and len(sentence) > 1:
        text = text[: len(text) - len(sentence)] + sentence[0].lower() + sentence[1:]

    # Close the sentence before appending another one, otherwise two
    # sentences run together and the tokeniser sees one long clause.
    tail = random.choice(NO_RESPONSE) + random.choice(POLITE_CLOSE)
    if tail and not text.rstrip().endswith((".", "!", "?")):
        text = text.rstrip() + "."
    text += tail

    text = text.strip()
    if not text.endswith((".", "!", "?")):
        text += "."
    return text[0].upper() + text[1:]


def build() -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    seen: set[str] = set()

    for category, frames in FRAMES.items():
        made = 0
        attempts = 0
        # Cap attempts so a category with few frames cannot loop forever.
        while made < PER_CATEGORY and attempts < PER_CATEGORY * 50:
            attempts += 1
            text = decorate(fill(random.choice(frames)))
            key = text.lower()
            if key in seen:
                continue
            seen.add(key)
            rows.append((text, category))
            made += 1

        if made < PER_CATEGORY:
            print(f"  warning: only {made} unique rows for {category}")

    random.shuffle(rows)
    return rows


